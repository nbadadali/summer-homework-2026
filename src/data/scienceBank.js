// Builds a 4-option multiple-choice question with distractors drawn from
// real answers elsewhere in the same part (deterministic-ish shuffle by seed
// so the same question doesn't reshuffle awkwardly mid-render).
export function buildMCQ(part, question, seedOffset = 0) {
  const others = part.questions.filter((q) => q.id !== question.id).map((q) => q.answer);
  const shuffled = [...others].sort(() => Math.random() - 0.5);
  const distractors = [...new Set(shuffled)].filter((a) => a !== question.answer).slice(0, 3);
  const options = [...distractors, question.answer].sort(() => Math.random() - 0.5);
  return { ...question, options };
}
